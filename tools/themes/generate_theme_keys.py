#!/usr/bin/env python3
"""
Generates WolvenKit.App/Resources/Themes/theme-keys.json from WolvenKit/Themes/App.Styles.xaml.

The catalog lists every color resource a theme may override, groups it for the theme editor,
and records which SolidColorBrush resources are derived from a Color via {StaticResource ...}.
Derived brushes have to be regenerated by the theme service, because StaticResource bakes the
original color into them when App.Styles.xaml is loaded.

Descriptions shown in the theme editor ("where is this color used") come from theme-key-descriptions.json
next to this script; quest / scene node keys get theirs from the key name.

Re-run after adding / renaming colors in App.Styles.xaml or editing the descriptions:
    python tools/themes/generate_theme_keys.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STYLES = ROOT / "WolvenKit" / "Themes" / "App.Styles.xaml"
OUT = ROOT / "WolvenKit.App" / "Resources" / "Themes" / "theme-keys.json"
DESCRIPTIONS = Path(__file__).resolve().parent / "theme-key-descriptions.json"

# Syncfusion MaterialDark surface brushes that WolvenKit views reference directly.
# Their defaults are read at runtime (they come from the Syncfusion theme assembly).
SYNCFUSION_KEYS = [
    "ContentBackground",
    "ContentBackgroundAlt",
    "ContentBackgroundAlt2",
    "ContentBackgroundAlt3",
    "ContentBackgroundAlt4",
    "ContentBackgroundAlt5",
    "ContentForeground",
    "ContentForegroundAlt1",
    "BorderAlt",
]

# HandyControl palette (hc:SearchBar, ButtonDefault, dialogs). "<Stem>Color" with derived "<Stem>Brush".
# The theme service links them to the Syncfusion surfaces, so themes don't have to set them explicitly.
HANDYCONTROL_STEMS = [
    "Primary", "DarkPrimary",
    "Region", "SecondaryRegion", "ThirdlyRegion", "Background",
    "Default", "DarkDefault",
    "Border", "SecondaryBorder",
    "PrimaryText", "SecondaryText", "ThirdlyText",
    "Title", "SecondaryTitle",
]

COLOR_RE = re.compile(r'<Color\s+x:Key="([^"]+)"\s*>([^<]+)</Color>')
BRUSH_RE = re.compile(r'<SolidColorBrush\s+x:Key="([^"]+)"\s+Color="([^"]+)"\s*/>')
# Only StaticResource bakes the color in. Brushes using DynamicResource follow their source by themselves
# (and BackgroundBrush_InputField even points a Color at a Brush, which throws when it is instantiated).
REF_RE = re.compile(r'\{StaticResource\s+([^}\s]+)\s*\}')
DYNAMIC_REF_RE = re.compile(r'\{DynamicResource\s+[^}\s]+\s*\}')


def group_of(key: str) -> str:
    if key.startswith("Quest"):
        return "Quest nodes"
    if key.startswith("Scene"):
        return "Scene nodes"
    if key.startswith("WolvenKitAccent") or key.startswith("WolvenKitStatusBar"):
        return "Accent"
    if key.startswith("WolvenKitProject"):
        return "Project Explorer"
    if key.startswith("WolvenKitGray"):
        return "Grays"
    if key.startswith("WolvenKitPanel"):
        return "Panels"
    if key.startswith("WolvenKitGraph"):
        return "Graph"
    if key.startswith("ForegroundColor"):
        return "Text"
    if key.startswith("BackgroundColor") or key.startswith("BackgroundBrush"):
        return "Backgrounds"
    if key.startswith("WolvenKit"):
        return "Palette"
    return "Misc"


def display_name(key: str) -> str:
    name = key
    if name.startswith("WolvenKit"):
        name = name[len("WolvenKit"):]
    if name.endswith("Color") and len(name) > len("Color"):
        name = name[: -len("Color")]
    name = name.replace("_", " ")
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", name)
    return " ".join(name.split())


NODE_RE = re.compile(r"^(Quest|Scene)(.+)Node(Header|Content)Color$")


def node_description(key: str) -> str | None:
    match = NODE_RE.match(key)
    if not match:
        return None
    graph, node, part = match.groups()
    node = " ".join(re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ", node).split())
    what = "header" if part == "Header" else "body"
    if node == "Default":
        return f"{graph} graph: {what} of nodes without a specific color"
    return f"{graph} graph: {what} of \"{node}\" nodes"


def main() -> int:
    text = STYLES.read_text(encoding="utf-8")

    entries: dict[str, dict] = {}
    derived: dict[str, list[str]] = {}

    for key, value in COLOR_RE.findall(text):
        entries[key] = {"key": key, "group": group_of(key), "displayName": display_name(key), "kind": "Color"}

    for key, color in BRUSH_RE.findall(text):
        ref = REF_RE.fullmatch(color.strip())
        if ref:
            derived.setdefault(ref.group(1), []).append(key)
            continue
        if DYNAMIC_REF_RE.fullmatch(color.strip()):
            continue
        if color.strip().lower() == "transparent":
            continue
        entries[key] = {"key": key, "group": group_of(key), "displayName": display_name(key), "kind": "Brush"}

    for stem in HANDYCONTROL_STEMS:
        entries[stem + "Color"] = {"key": stem + "Color", "group": "HandyControl", "displayName": display_name(stem),
                                   "kind": "Color", "derivedBrushes": [stem + "Brush"]}

    for key in SYNCFUSION_KEYS:
        entries[key] = {"key": key, "group": "Surfaces", "displayName": display_name(key), "kind": "Brush"}

    descriptions = json.loads(DESCRIPTIONS.read_text(encoding="utf-8")) if DESCRIPTIONS.exists() else {}
    for key, entry in entries.items():
        description = descriptions.get(key) or node_description(key)
        if description:
            entry["description"] = description
        else:
            print(f"note: no description for {key}", file=sys.stderr)
    for key in descriptions:
        if key not in entries:
            print(f"note: description for unknown key {key}", file=sys.stderr)

    for key, brushes in derived.items():
        if key in entries:
            entries[key]["derivedBrushes"] = brushes
        else:
            print(f"warning: {brushes} derive from unknown key {key}", file=sys.stderr)

    order = ["Accent", "Surfaces", "Panels", "Grays", "Project Explorer", "HandyControl", "Text", "Backgrounds", "Palette", "Graph", "Quest nodes", "Scene nodes", "Misc"]
    result = sorted(entries.values(), key=lambda e: (order.index(e["group"]), list(entries).index(e["key"])))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"entries": result}, indent=2) + "\n", encoding="utf-8")
    print(f"{len(result)} entries, {sum(len(v) for v in derived.values())} derived brushes -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
